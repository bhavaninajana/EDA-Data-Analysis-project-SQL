-- Ranking Analysis 
/*Order the values of dimensions by measure. Top N performers | Bottom N Performers. RANK[Dimension] BY aggreagted Measure*/
/* ex: Rank countries by total sales, Top5  products by quantity, Bottom 3 customers by total orders. To solve these we can use either TOP function or RANK, DENSE_RANK,ROW_NUMBER*/

-- Which 5 products generate the highest revenue
SELECT TOP 5
p.product_name,
SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p
ON f.product_key= p.product_key
GROUP BY p.product_name
ORDER BY total_revenue DESC

-- Solving the same question using windows functions such as ROW_NUMBER 
SELECT 
*
FROM(
	SELECT
	p.product_name,
	SUM(f.sales_amount) AS total_revenue,
	ROW_NUMBER() OVER(ORDER BY SUM(f.sales_amount) DESC) AS rank_products
	FROM gold.fact_sales f
	LEFT JOIN gold.dim_products p
	ON f.product_key= p.product_key
	GROUP BY p.product_name)t
WHERE rank_products <=5

-- What are the 5 worst-performing proucts in terms of sales?

