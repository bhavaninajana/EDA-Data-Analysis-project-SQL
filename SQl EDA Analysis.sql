-- Change over time analysis 
/*Analyze how a measure evolves over time. Helps track trends and identify seasonality in your data. (Measure By [Date Dimension]) ex: Total Sales by Year, Average cost by month ?*/
--Change over years (A higher-level overview insights that helps with strategic decision making)
SELECT 
YEAR(order_date) AS order_year,
SUM(sales_amount) AS total_sales,
COUNT(DISTINCT customer_key) AS total_customers,
SUM(quantity) AS total_quantity
FROM gold.fact_sales
WHERE order_date IS NOT NULL
GROUP BY YEAR(order_date)
ORDER BY YEAR(order_date)

-- Change over months (Detailed insights to discover seasonality in your data)
SELECT 
MONTH(order_date) AS order_month,
SUM(sales_amount) AS total_sales,
COUNT(DISTINCT customer_key) AS total_customers,
SUM(quantity) AS total_quantity
FROM gold.fact_sales
WHERE order_date IS NOT NULL
GROUP BY MONTH(order_date)
ORDER BY MONTH(order_date)

-- Cumulative Analysis 
/* Aggregate the data progressively over time. Helps to understand whether our business is growing or declining.(Cumulative measure By [Date Column] ex: Running total sales by year, moving average of sales by month( to do this type of analysis we use Aggregate window functions)*/

-- Calculate the total sales per month and the running total of sales over time
SELECT
order_date,
total_sales,
SUM(total_sales) OVER (PARTITION BY order_date ORDER BY order_date) AS running_total_sales
FROM(
	SELECT 
	DATETRUNC(month,order_date) AS order_date,
	SUM(sales_amount) AS total_sales
	FROM gold.fact_sales
	WHERE order_date IS NOT NULL
	GROUP BY DATETRUNC(month,order_date) 
	)t


